/**
 * 渠道名数组 → [{ name, desc }]
 * @param {string[]} names 来自规则表的渠道名
 * @param {object|null} category 规则表品类对象（取 group）
 * @param {number} [limit] 结果页一屏放得下 1–2 个（规格 2.3 分支 B），默认 2
 */
export function describeChannels(names, category, limit = 2) {
  const list = Array.isArray(names) ? names : []
  return list.slice(0, limit).map(name => ({
    name,
    desc: BY_CHANNEL[name] || (category && BY_GROUP[category.group]) || '按平台规则发布，描述里写清成色和瑕疵。'
  }))
}

